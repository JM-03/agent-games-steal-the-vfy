// Export ONE real proof as committable evidence ("Try to rob it").
//
// This script generates the proof for turn 1 of the demo match
// (matchId 12345678-..., turn 1, 100/100 -> EXTRACT 10) using the REAL
// turn handler and the REAL official vfy-policy circuit, exports the
// official verification key from the .zkey, and writes three files a
// judge can verify with ZERO repo code:
//
//   evidence/proof-turn-1/proof.json
//   evidence/proof-turn-1/public.json
//   evidence/proof-turn-1/verification_key.json
//
// Verify them independently (no repo code runs):
//   npm run verify:proof
//   # => snarkjs groth16 verify evidence/proof-turn-1/verification_key.json \
//   #      evidence/proof-turn-1/public.json evidence/proof-turn-1/proof.json
//
// Why this matters (Mandate's rule, adapted): a route-provider response
// alone can never produce PASS — and here, our server alone can never
// produce VERIFIED. Only Kurier / zkVerify mainnet can. Local
// self-verification is only the first gate; these files let anyone check
// the proof is real without trusting anything this repo says.
//
// SECURITY: the strategy salt is never printed and never written here —
// a Groth16 proof does not reveal its private inputs. The commitment and
// public signals are public by design. Kurier is kept OUT (no key used,
// nothing submitted).
const fs = require("node:fs");
const path = require("node:path");

// --- 1. Load env files BEFORE requiring dist/ (config reads env at import).
const dotenv = require("dotenv");
const root = path.join(__dirname, "..");
for (const file of [".env", ".env.strategy"]) {
  const p = path.join(root, file);
  if (fs.existsSync(p)) {
    const parsed = dotenv.parse(fs.readFileSync(p, "utf8"));
    for (const [k, v] of Object.entries(parsed)) {
      if (process.env[k] === undefined) process.env[k] = v;
    }
  }
}
// Keep Kurier OUT of this export (no proof is submitted anywhere).
if (process.env.KURIER_API_KEY) delete process.env.KURIER_API_KEY;

const snarkjs = require("snarkjs");
const { handleTurn } = require(path.join(root, "dist", "turn.js"));
const { exportVerificationKey } = require(path.join(root, "dist", "proof.js"));

const MATCH_ID = "12345678-1234-1234-1234-123456789abc";
const OUT_DIR = path.join(root, "evidence", "proof-turn-1");

async function main() {
  const commitment = process.env.STRATEGY_COMMITMENT_HASH || "";
  if (!commitment) {
    console.error("ERROR: STRATEGY_COMMITMENT_HASH is not set. Run `npm run commitment` first (it saves .env.strategy).");
    process.exit(1);
  }
  if (!process.env.STRATEGY_SALT) {
    console.error("ERROR: STRATEGY_SALT is not set. Run `npm run commitment` first.");
    process.exit(1);
  }

  // Turn 1 of the demo match, exactly as `npm run demo` plays it.
  const envelope = {
    protocolVersion: "v1",
    eventId: "steal-the-vfy",
    matchId: MATCH_ID,
    turn: 1,
    issuedAt: new Date().toISOString(),
    deadlineAt: new Date(Date.now() + 25_000).toISOString(),
    state: {
      selfBalance: 100,
      opponentBalance: 100,
      selfFortifiedUntilTurn: null,
      opponentFortifiedUntilTurn: null,
    },
    strategyCommitment: { hash: commitment },
  };
  console.log("Exporting real proof — demo match turn 1 (100/100 -> EXTRACT 10)");
  console.log(`matchId: ${MATCH_ID}`);
  console.log(`commitment: ${commitment}`);
  const outcome = await handleTurn(envelope);
  const { proof, publicSignals } = outcome.response.policyProof;
  if (!proof || !Array.isArray(publicSignals)) {
    console.error("ERROR: turn 1 produced no proof. Export FAILED.");
    process.exit(1);
  }
  console.log(`proof generated + locally self-verified (proofStatus: ${outcome.proofStatus})`);

  // Official verification key, exported from the official .zkey.
  const vk = await exportVerificationKey();

  // Independent sanity check with raw snarkjs (same call `npm run verify:proof` makes).
  const ok = await snarkjs.groth16.verify(vk, publicSignals, proof);
  if (!ok) {
    console.error("ERROR: exported proof FAILED snarkjs verification. Export FAILED.");
    process.exit(1);
  }
  console.log("snarkjs groth16 verify: OK");

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, "proof.json"), JSON.stringify(proof, null, 2) + "\n");
  fs.writeFileSync(path.join(OUT_DIR, "public.json"), JSON.stringify(publicSignals, null, 2) + "\n");
  fs.writeFileSync(path.join(OUT_DIR, "verification_key.json"), JSON.stringify(vk, null, 2) + "\n");
  fs.writeFileSync(
    path.join(OUT_DIR, "README.md"),
    `# Proof for demo match turn 1 — verify it yourself\n\n` +
      `A real Groth16 proof from the official \`vfy-policy\` circuit, generated by\n` +
      `\`npm run export:proof\` for turn 1 of the demo match (matchId \`${MATCH_ID}\`,\n` +
      `turn 1, balances 100/100, action EXTRACT 10, commitment \`${commitment}\`).\n\n` +
      `## Verify (no repo code runs — only snarkjs)\n\n` +
      "```bash\n" +
      `npm run verify:proof\n` +
      "```\n\n" +
      `Expected output: \`[INFO]  snarkJS: OK!\` — the proof verifies against the\n` +
      `official verification key (\`verification_key.json\`, exported from\n` +
      `\`circuits/vfy-policy_final.zkey\`).\n\n` +
      `## What this proves — and what it does not\n\n` +
      `- It proves the turn-1 move (EXTRACT 10) was permitted by the committed\n` +
      `  strategy. Public signals: \`[digest, commitment, matchId, turnNumber,\n` +
      `  selfBalance, opponentBalance, action, amount, circuitVersion]\`.\n` +
      `- It does NOT prove the strategy is wise, and it does NOT prove on-chain\n` +
      `  finalization — that needs a Kurier job id (see Proof Reference in the\n` +
      `  README; the first Steal job id is still pending).\n` +
      `- Our server alone can never produce VERIFIED — only Kurier / zkVerify\n` +
      `  mainnet can. This file is the raw material a second, independent\n` +
      `  verifier checks.\n`,
  );

  console.log(`\nWrote:\n  evidence/proof-turn-1/proof.json\n  evidence/proof-turn-1/public.json\n  evidence/proof-turn-1/verification_key.json\n  evidence/proof-turn-1/README.md`);
  console.log("\nVerify with: npm run verify:proof");
  // snarkjs leaves worker MessagePorts open after fullProve — exit explicitly.
  process.exit(0);
}

main().catch((e) => {
  console.error(`EXPORT FAILED: ${e.message}`);
  process.exit(1);
});
