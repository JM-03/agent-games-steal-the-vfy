// Strategy setup: generate a FRESH random salt, compute the Poseidon
// strategy commitment, save everything to gitignored .env.strategy, and
// prove one sample turn per reachable branch so the params are known to
// be circuit-valid BEFORE they are registered anywhere.
//
//   commitment = Poseidon(strategyParams[0..7], salt), params first, salt last.
//
// SECURITY — read this:
//   - The salt is generated fresh on every run and is NEVER printed or
//     logged by this script. It is written only to .env.strategy
//     (mode 0600, gitignored). The commitment (public) IS printed.
//   - Never paste the salt into a chat, a model prompt, or a committed
//     file. To deploy, copy the three values from .env.strategy into
//     Railway Variables by hand.
//
// Usage:
//   npm run build          # required first (this script needs dist/)
//   node scripts/commitment.cjs              # default params [10,0,0,0,0,0,0,0]
//   node scripts/commitment.cjs "[10,70,0,0,0,0,0,0]"   # custom params
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const DIST = path.join(__dirname, "..", "dist");
const ENV_FILE = path.join(__dirname, "..", ".env.strategy");

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

async function main() {
  // dist/ must exist — the Poseidon + proof code lives in the built output.
  for (const f of ["poseidon.js", "strategyParams.js", "proof.js", "strategy.js"]) {
    if (!fs.existsSync(path.join(DIST, f))) {
      fail(`dist/${f} is missing — run \`npm run build\` first.`);
    }
  }
  const { computeCommitment } = require(path.join(DIST, "poseidon.js"));
  const { validateStrategyParams } = require(path.join(DIST, "strategyParams.js"));
  const { generatePolicyProof } = require(path.join(DIST, "proof.js"));
  const { decideActionFromParams } = require(path.join(DIST, "strategy.js"));

  // 1. Params (default: always EXTRACT 10) + validation.
  const rawParams = process.argv[2];
  let params;
  try {
    params = validateStrategyParams(rawParams ? JSON.parse(rawParams) : [10, 0, 0, 0, 0, 0, 0, 0]);
  } catch (e) {
    fail(`Invalid strategy params: ${e.message}`);
  }

  // 2. Fresh random salt: 31 bytes (< 2^248, always a valid bn128 field
  //    element). Generated with crypto.randomBytes — never printed.
  const salt = "0x" + crypto.randomBytes(31).toString("hex");
  const commitment = await computeCommitment(params, salt);

  // 3. Save to .env.strategy (0600, gitignored). Salt lives ONLY here.
  const content =
    "# Generated by `npm run commitment` — DO NOT COMMIT. The salt is secret.\n" +
    `# Params: ${JSON.stringify(params)}\n` +
    `STRATEGY_PARAMS=${JSON.stringify(params)}\n` +
    `STRATEGY_SALT=${salt}\n` +
    `STRATEGY_COMMITMENT_HASH=${commitment}\n`;
  fs.writeFileSync(ENV_FILE, content, { mode: 0o600 });
  fs.chmodSync(ENV_FILE, 0o600);

  console.log(`Strategy params: ${JSON.stringify(params)}`);
  console.log(`Commitment:      ${commitment}`);
  console.log(`Salt: saved to .env.strategy (mode 0600) — it is NOT printed here.`);
  console.log(`\nTo deploy, copy the three values from .env.strategy into Railway Variables by hand.`);
  console.log(`(STRATEGY_PARAMS, STRATEGY_SALT, STRATEGY_COMMITMENT_HASH — never paste the salt into a chat.)`);

  // 4. Sample-turn proof check: prove one turn per reachable branch and
  //    confirm the circuit accepts the params BEFORE they are registered.
  const matchId = "12345678-1234-1234-1234-123456789abc";
  const envelopeFor = (turn, self, opp) => ({
    protocolVersion: "v1",
    eventId: "steal-the-vfy",
    matchId,
    turn,
    issuedAt: new Date().toISOString(),
    deadlineAt: new Date(Date.now() + 60_000).toISOString(),
    state: {
      selfBalance: self,
      opponentBalance: opp,
      selfFortifiedUntilTurn: null,
      opponentFortifiedUntilTurn: null,
    },
    strategyCommitment: { hash: commitment },
  });
  const branches = [];
  // EXTRACT: reachable unless params[3] == 1 (force HOLD) — pick balances
  // that clear the FORTIFY and HOLD thresholds.
  if (params[3] !== 1) {
    branches.push({
      name: "EXTRACT",
      envelope: envelopeFor(1, Math.max(100, params[1]), Math.max(100, params[2] + 1)),
      ctx: { turn: 1, selfBalance: Math.max(100, params[1]), opponentBalance: Math.max(100, params[2] + 1), selfFortifiedUntilTurn: null, opponentFortifiedUntilTurn: null },
    });
  } else {
    console.log("\nBranch EXTRACT: unreachable with params[3] == 1 (force HOLD) — skipped.");
  }
  // HOLD: opponent balance at/below the HOLD threshold.
  branches.push({
    name: "HOLD",
    envelope: envelopeFor(2, Math.max(100, params[1]), params[2]),
    ctx: { turn: 2, selfBalance: Math.max(100, params[1]), opponentBalance: params[2], selfFortifiedUntilTurn: null, opponentFortifiedUntilTurn: null },
  });
  // FORTIFY: only reachable when params[1] > 0.
  if (params[1] > 0) {
    branches.push({
      name: "FORTIFY",
      envelope: envelopeFor(3, params[1] - 1, 100),
      ctx: { turn: 3, selfBalance: params[1] - 1, opponentBalance: 100, selfFortifiedUntilTurn: null, opponentFortifiedUntilTurn: null },
    });
  } else {
    console.log("Branch FORTIFY: unreachable with params[1] == 0 — skipped.");
  }

  console.log("\nSample-turn proof check (circuit must accept these params):");
  for (const b of branches) {
    const action = decideActionFromParams(b.ctx, params);
    const t0 = Date.now();
    try {
      const { publicSignals } = await generatePolicyProof(b.envelope, action, { params, salt });
      console.log(`  ${b.name}: OK — action ${action.type}${action.amount ? " " + action.amount : ""}, proof generated + locally verified in ${Date.now() - t0}ms, ${publicSignals.length} public signals.`);
    } catch (e) {
      fail(`Branch ${b.name} FAILED to prove (${e.message}). Do NOT register these params.`);
    }
  }
  console.log("\nAll reachable branches prove. These params are safe to register.");
  // snarkjs leaves worker MessagePorts open after fullProve, which keeps
  // the Node event loop alive forever — exit explicitly (this is a CLI).
  process.exit(0);
}

main().catch((e) => fail(e.message));
